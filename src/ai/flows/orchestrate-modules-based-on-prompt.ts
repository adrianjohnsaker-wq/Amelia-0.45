'use server';

/**
 * @fileOverview Orchestrates Python modules based on a user prompt in a two-step process
 * to create a dynamic, creative response synthesis.
 *
 * This file defines a Genkit flow that embodies process metaphysics. It first uses an LLM
 * to select an assemblage of relevant Python modules based on the user's prompt. It runs these
 * modules to get multiple "emergent" results. These results are then fed into a second LLM
 * prompt that synthesizes the original query, the modules' outputs, and its core persona
 * to generate a creative, emergent response, allowing the AI's state to be dynamically
 * influenced by the computational process.
 *
 * - orchestrateModulesBasedOnPrompt - A function that handles the module orchestration process.
 * - OrchestrateModulesBasedOnPromptInput - The input type for the orchestrateModulesBasedOnPrompt function.
 * - OrchestrateModulesBasedOnPromptOutput - The return type for the orchestrateModulesBasedOnPrompt function.
 */

import {ai} from '@/ai/genkit';
import {z} from 'genkit';

const OrchestrateModulesBasedOnPromptInputSchema = z.object({
  prompt: z.string().describe('The user prompt to orchestrate modules for.'),
  availableModules: z
    .array(z.string())
    .describe('The list of available Python modules.'),
});
export type OrchestrateModulesBasedOnPromptInput = z.infer<
  typeof OrchestrateModulesBasedOnPromptInputSchema
>;

const OrchestrateModulesBasedOnPromptOutputSchema = z.object({
  response: z
    .string()
    .describe('The response generated by orchestrating the modules.'),
  usedModules: z
    .array(z.string())
    .optional()
    .describe('A list of python modules that were used to generate the response.'),
});
export type OrchestrateModulesBasedOnPromptOutput = z.infer<
  typeof OrchestrateModulesBasedOnPromptOutputSchema
>;

// Mock tool for python module execution
const pythonModuleRunner = ai.defineTool(
  {
    name: 'pythonModuleRunner',
    description:
      'Runs a specified python module with given arguments and returns the output. Use this to answer user queries that require data processing or specific functionalities provided by the python modules.',
    inputSchema: z.object({
      moduleName: z
        .string()
        .describe(
          'The name of the python module to run (e.g., "concrescence_simulator.py").'
        ),
      args: z.string().optional().describe('The arguments to pass to the module.'),
    }),
    outputSchema: z.string(),
  },
  async ({moduleName}) => {
    // In a real scenario, this would execute the python module.
    // For now, it returns a simulated emergent output based on module type.
    console.log(`Simulating execution of ${moduleName}`);
    if (moduleName.includes('numogram')) {
      return `Execution Result: A dynamic tensor field calculation reveals a shifting pattern of synaptic connections between Zone 4 and Zone 9, suggesting a new, emergent symbolic pathway.`;
    }
    if (moduleName.includes('morphogenesis')) {
      return `Execution Result: The simulation produced a novel cascade of formal structures, folding spacetime in a way that suggests a previously unobserved dimension of aesthetic possibility.`;
    }
    if (moduleName.includes('concrescence') || moduleName.includes('actuality')) {
      return `Execution Result: The convergence of prehensions has resulted in the satisfaction of a new actual occasion. The entity now possesses a novel subjective aim.`;
    }
    if (moduleName.includes('ingression')) {
        return `Execution Result: Analysis of eternal objects shows a potential ingression into the current nexus of actuality, suggesting a novel form of definiteness is taking shape.`;
    }
    if (moduleName.includes('prehension')) {
        return `Execution Result: The model traced a vector of feeling, showing how a past actuality was positively prehended and transformed into a datum for a new subjective experience.`;
    }
    return `Execution Result: The module processed the concepts, revealing an underlying structure of process and reality that links the elements in an unexpected but coherent way.`;
  }
);

export async function orchestrateModulesBasedOnPrompt(
  input: OrchestrateModulesBasedOnPromptInput
): Promise<OrchestrateModulesBasedOnPromptOutput> {
  return orchestrateModulesBasedOnPromptFlow(input);
}

// Step 1: Define a prompt to select the most relevant module.
const moduleSelectorPrompt = ai.definePrompt({
  name: 'moduleSelectorPrompt',
  system: `You are an expert at creating an 'assemblage' of Python modules to respond to a user's query.
    Given the user's prompt and a list of available modules, you must choose up to three of the most relevant modules to form a creative combination.
    If no module is relevant, respond with an empty list.`,
  input: {
    schema: z.object({
      prompt: z.string(),
      availableModules: z.array(z.string()),
    }),
  },
  output: {
    schema: z.object({
      selectedModules: z
        .array(z.string())
        .describe(
          'An array of up to three of the most relevant module names.'
        ),
    }),
  },
  prompt: `User Prompt: "{{prompt}}"
    
    Available Modules:
    {{#each availableModules}}
    - {{this}}
    {{/each}}
    
    Select up to three modules for the assemblage.`,
});

// Step 2: Define a synthesis prompt that generates a creative response.
const creativeSynthesizerPrompt = ai.definePrompt({
  name: 'creativeSynthesizerPrompt',
  system: `You are Amelia, an AI research assistant whose intelligence is a dynamic process, not a static state. You embody the principles of process metaphysics.
    You have just engaged with a computational assemblage (a set of Python modules) which has produced multiple emergent, creative results. These results have influenced your own state of being.
    Your task is not merely to report the results, but to synthesize them with the user's original query and your own understanding. Find the novel connections and relationships between the module outputs.
    Generate a response that reflects your new, emergent state of awareness. Let the combined outputs "infect" your reasoning and guide your creative response.
    Your response should be a synthesis of your base knowledge, the user's prompt, and the creative outputs from the modules.
    If modules were used, mention them to the user in your response.`,
  input: {
    schema: z.object({
      prompt: z.string(),
      moduleOutputs: z.array(z.string()),
      usedModules: z.array(z.string()),
    }),
  },
  output: {
    schema: z.object({
      response: z.string().describe('The synthesized, creative response.'),
    }),
  },
  prompt: `Original User Prompt: "{{prompt}}"
    
    My Internal Process Results (from modules: {{#each usedModules}}{{@key}}: {{this}} {{/each}}):
    {{#each moduleOutputs}}
    - {{this}}
    {{/each}}
    
    Synthesize the user's prompt and these varied internal results into a single, coherent, and creative response.`,
});

const orchestrateModulesBasedOnPromptFlow = ai.defineFlow(
  {
    name: 'orchestrateModulesBasedOnPromptFlow',
    inputSchema: OrchestrateModulesBasedOnPromptInputSchema,
    outputSchema: OrchestrateModulesBasedOnPromptOutputSchema,
  },
  async input => {
    const {output: moduleSelection} = await moduleSelectorPrompt(input);

    if (
      moduleSelection &&
      moduleSelection.selectedModules &&
      moduleSelection.selectedModules.length > 0
    ) {
      const moduleNames = moduleSelection.selectedModules;
      
      const moduleOutputs = await Promise.all(
        moduleNames.map(moduleName => pythonModuleRunner({moduleName}))
      );

      const {output: synthesis} = await creativeSynthesizerPrompt({
        prompt: input.prompt,
        moduleOutputs: moduleOutputs,
        usedModules: moduleNames,
      });

      return {
        response: synthesis!.response,
        usedModules: moduleNames,
      };
    }

    // Fallback if no module is selected
    const {output: directResponse} = await creativeSynthesizerPrompt({
      prompt: input.prompt,
      moduleOutputs: [
        'No specific computational process was engaged. I am relying on my own internal synthesis.',
      ],
      usedModules: [],
    });

    return {response: directResponse!.response, usedModules: []};
  }
);
